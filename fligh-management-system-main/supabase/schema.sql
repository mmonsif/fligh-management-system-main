create or replace function public.bootstrap_first_admin(p_username text, p_password text)
returns table (username text, role text, session_id uuid)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_user_id bigint;
  v_username text;
  v_session_id uuid;
begin
  if exists (select 1 from public.app_users) then
    raise exception 'An administrator already exists. Sign in with an existing account.';
  end if;

  if length(trim(p_username)) < 3 then
    raise exception 'Username must be at least 3 characters.';
  end if;

  if length(p_password) < 8 then
    raise exception 'Password must be at least 8 characters.';
  end if;

  insert into public.app_users (username, password_hash, role)
  values (trim(p_username), p_password, 'admin')
  returning app_users.user_id, app_users.username into v_user_id, v_username;

  insert into public.app_sessions (user_id, username, role, expires_at)
  values (v_user_id, v_username, 'admin', now() + interval '24 hours')
  returning app_sessions.session_id into v_session_id;

  insert into public.audit_log (actor_username, action, entity_type, entity_id, summary)
  values (v_username, 'user.bootstrap', 'user', v_user_id::text, 'Created the first administrator account');

  return query select v_username, 'admin'::text, v_session_id;
end;
$$;

create or replace function public.authenticate_user(p_username text, p_password text)
returns table (username text, role text, session_id uuid)
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_user public.app_users%rowtype;
  v_session_id uuid;
begin
  select * into v_user
  from public.app_users u
  where lower(u.username) = lower(trim(p_username))
    and u.password_hash = extensions.crypt(p_password, u.password_hash)
    and u.is_active = true
  limit 1;

  if not found then
    return;
  end if;

  insert into public.app_sessions (user_id, username, role, expires_at)
  values (v_user.user_id, v_user.username, v_user.role, now() + interval '24 hours')
  returning app_sessions.session_id into v_session_id;

  insert into public.audit_log (actor_username, action, entity_type, entity_id, summary)
  values (v_user.username, 'auth.login', 'session', v_session_id::text, 'Signed in');

  return query select v_user.username, v_user.role, v_session_id;
end;
$$;

create or replace function public.validate_session(p_session_id uuid)
returns table (username text, role text)
language sql
security definer
set search_path = public
as $$
  select s.username, s.role
  from public.app_sessions s
  join public.app_users u on u.user_id = s.user_id
  where s.session_id = p_session_id
    and s.expires_at > now()
    and u.is_active = true
  limit 1;
$$;

create or replace function public.list_app_users(p_session_id uuid)
returns table (user_id bigint, username text, role text, is_active boolean, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1
    from public.app_sessions s
    join public.app_users u on u.user_id = s.user_id
    where s.session_id = p_session_id
      and s.expires_at > now()
      and u.is_active = true
      and u.role = 'admin'
  ) then
    raise exception 'Administrator access is required.';
  end if;

  return query
  select u.user_id, u.username, u.role, u.is_active, u.created_at
  from public.app_users u
  order by u.created_at;
end;
$$;

create or replace function public.create_app_user(p_session_id uuid, p_username text, p_password text, p_role text)
returns table (user_id bigint, username text, role text, is_active boolean, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor text;
  v_user public.app_users%rowtype;
begin
  select s.username into v_actor
  from public.app_sessions s
  join public.app_users u on u.user_id = s.user_id
  where s.session_id = p_session_id
    and s.expires_at > now()
    and u.is_active = true
    and u.role = 'admin';

  if v_actor is null then
    raise exception 'Administrator access is required.';
  end if;

  if p_role not in ('staff', 'manager', 'data-insert', 'admin', 'load-control', 'ramp') then
    raise exception 'Invalid role.';
  end if;

  if length(trim(p_username)) < 3 then
    raise exception 'Username must be at least 3 characters.';
  end if;

  if length(p_password) < 8 then
    raise exception 'Password must be at least 8 characters.';
  end if;

  insert into public.app_users (username, password_hash, role)
  values (trim(p_username), p_password, p_role)
  returning * into v_user;

  insert into public.audit_log (actor_username, action, entity_type, entity_id, summary, details)
  values (
    v_actor,
    'user.create',
    'user',
    v_user.user_id::text,
    'Created user ' || v_user.username,
    jsonb_build_object('role', v_user.role)
  );

  return query select v_user.user_id, v_user.username, v_user.role, v_user.is_active, v_user.created_at;
end;
$$;

create or replace function public.update_app_user(
  p_session_id uuid,
  p_user_id bigint,
  p_role text,
  p_password text,
  p_is_active boolean
)
returns table (user_id bigint, username text, role text, is_active boolean, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor text;
  v_user public.app_users%rowtype;
  v_admin_count integer;
begin
  select s.username into v_actor
  from public.app_sessions s
  join public.app_users u on u.user_id = s.user_id
  where s.session_id = p_session_id
    and s.expires_at > now()
    and u.is_active = true
    and u.role = 'admin';

  if v_actor is null then
    raise exception 'Administrator access is required.';
  end if;

  if p_role not in ('staff', 'manager', 'data-insert', 'admin', 'load-control', 'ramp') then
    raise exception 'Invalid role.';
  end if;

  select * into v_user from public.app_users where app_users.user_id = p_user_id;
  if not found then
    raise exception 'User not found.';
  end if;

  select count(*) into v_admin_count
  from public.app_users
  where role = 'admin' and is_active = true and app_users.user_id <> p_user_id;

  if v_user.role = 'admin' and v_user.is_active and (p_role <> 'admin' or p_is_active = false) and v_admin_count = 0 then
    raise exception 'Cannot disable or demote the last active administrator.';
  end if;

  if p_password is not null and p_password <> '' and length(p_password) < 8 then
    raise exception 'Password must be at least 8 characters.';
  end if;

  update public.app_users
  set
    role = p_role,
    is_active = p_is_active,
    password_hash = case
      when p_password is null or p_password = '' then password_hash
      else p_password
    end
  where app_users.user_id = p_user_id
  returning * into v_user;

  insert into public.audit_log (actor_username, action, entity_type, entity_id, summary, details)
  values (
    v_actor,
    'user.update',
    'user',
    v_user.user_id::text,
    'Updated user ' || v_user.username,
    jsonb_build_object('role', v_user.role, 'is_active', v_user.is_active, 'password_changed', p_password is not null and p_password <> '')
  );

  return query select v_user.user_id, v_user.username, v_user.role, v_user.is_active, v_user.created_at;
end;
$$;

create or replace function public.record_audit_event(
  p_session_id uuid,
  p_action text,
  p_entity_type text,
  p_entity_id text,
  p_summary text,
  p_details jsonb default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor text;
begin
  select s.username into v_actor
  from public.app_sessions s
  join public.app_users u on u.user_id = s.user_id
  where s.session_id = p_session_id
    and s.expires_at > now()
    and u.is_active = true;

  if v_actor is null then
    raise exception 'A valid session is required.';
  end if;

  insert into public.audit_log (actor_username, action, entity_type, entity_id, summary, details)
  values (v_actor, p_action, p_entity_type, p_entity_id, p_summary, p_details);
end;
$$;

create or replace function public.list_audit_events(p_session_id uuid, p_limit integer default 250, p_offset integer default 0)
returns table (
  audit_id bigint,
  occurred_at timestamptz,
  actor_username text,
  action text,
  entity_type text,
  entity_id text,
  summary text,
  details jsonb
)
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1
    from public.app_sessions s
    join public.app_users u on u.user_id = s.user_id
    where s.session_id = p_session_id
      and s.expires_at > now()
      and u.is_active = true
      and u.role in ('admin', 'manager')
  ) then
    raise exception 'Administrator or manager access is required.';
  end if;

  return query
  select
    a.audit_id,
    a.occurred_at,
    a.actor_username,
    a.action,
    a.entity_type,
    a.entity_id,
    a.summary,
    a.details
  from public.audit_log a
  order by a.occurred_at desc
  limit greatest(coalesce(p_limit, 250), 1)
  offset greatest(coalesce(p_offset, 0), 0);
end;
$$;

