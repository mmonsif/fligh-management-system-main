-- Additive migration: Loading Instruction Reports (LIR) and load-control / ramp roles.
-- Run in Supabase Dashboard > SQL Editor on an existing database. Safe to re-run.

-- Allow Load Control and Ramp accounts without rebuilding app_users.
alter table public.app_users drop constraint if exists app_users_role_check;
alter table public.app_users
  add constraint app_users_role_check
  check (role in ('staff', 'manager', 'data-insert', 'admin', 'load-control', 'ramp'));

create or replace function public.create_app_user(p_session_id uuid, p_username text, p_password text, p_role text)
returns table (user_id bigint, username text, role text, is_active boolean, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor text;
  v_user public.app_users%rowtype;
begin
  select s.username into v_actor
  from public.app_sessions s
  join public.app_users u on u.user_id = s.user_id
  where s.session_id = p_session_id
    and s.expires_at > now()
    and u.is_active = true
    and u.role = 'admin';

  if v_actor is null then
    raise exception 'Administrator access is required.';
  end if;

  if p_role not in ('staff', 'manager', 'data-insert', 'admin', 'load-control', 'ramp') then
    raise exception 'Invalid role.';
  end if;

  if length(trim(p_username)) < 3 then
    raise exception 'Username must be at least 3 characters.';
  end if;

  if length(p_password) < 8 then
    raise exception 'Password must be at least 8 characters.';
  end if;

  insert into public.app_users (username, password_hash, role)
  values (trim(p_username), p_password, p_role)
  returning * into v_user;

  insert into public.audit_log (actor_username, action, entity_type, entity_id, summary, details)
  values (
    v_actor,
    'user.create',
    'user',
    v_user.user_id::text,
    'Created user ' || v_user.username,
    jsonb_build_object('role', v_user.role)
  );

  return query select v_user.user_id, v_user.username, v_user.role, v_user.is_active, v_user.created_at;
end;
$$;

create or replace function public.update_app_user(
  p_session_id uuid,
  p_user_id bigint,
  p_role text,
  p_password text,
  p_is_active boolean
)
returns table (user_id bigint, username text, role text, is_active boolean, created_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_actor text;
  v_user public.app_users%rowtype;
  v_admin_count integer;
begin
  select s.username into v_actor
  from public.app_sessions s
  join public.app_users u on u.user_id = s.user_id
  where s.session_id = p_session_id
    and s.expires_at > now()
    and u.is_active = true
    and u.role = 'admin';

  if v_actor is null then
    raise exception 'Administrator access is required.';
  end if;

  if p_role not in ('staff', 'manager', 'data-insert', 'admin', 'load-control', 'ramp') then
    raise exception 'Invalid role.';
  end if;

  select * into v_user from public.app_users where app_users.user_id = p_user_id;
  if not found then
    raise exception 'User not found.';
  end if;

  select count(*) into v_admin_count
  from public.app_users
  where role = 'admin' and is_active = true and app_users.user_id <> p_user_id;

  if v_user.role = 'admin' and v_user.is_active and (p_role <> 'admin' or p_is_active = false) and v_admin_count = 0 then
    raise exception 'Cannot disable or demote the last active administrator.';
  end if;

  if p_password is not null and p_password <> '' and length(p_password) < 8 then
    raise exception 'Password must be at least 8 characters.';
  end if;

  update public.app_users
  set
    role = p_role,
    is_active = p_is_active,
    password_hash = case
      when p_password is null or p_password = '' then password_hash
      else p_password
    end
  where app_users.user_id = p_user_id
  returning * into v_user;

  insert into public.audit_log (actor_username, action, entity_type, entity_id, summary, details)
  values (
    v_actor,
    'user.update',
    'user',
    v_user.user_id::text,
    'Updated user ' || v_user.username,
    jsonb_build_object('role', v_user.role, 'is_active', v_user.is_active, 'password_changed', p_password is not null and p_password <> '')
  );

  return query select v_user.user_id, v_user.username, v_user.role, v_user.is_active, v_user.created_at;
end;
$$;

create table if not exists public.loading_instructions (
  lir_id bigint generated by default as identity primary key,
  flight_id bigint not null unique references public.flights(flight_id) on delete cascade,
  status text not null default 'draft' check (status in ('draft', 'planned', 'actual', 'approved')),
  deviation_notes text not null default '',
  load_control_notes text not null default '',
  planned_by text,
  planned_at timestamptz,
  actual_by text,
  actual_at timestamptz,
  approved_by text,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.loading_instruction_holds (
  hold_id bigint generated by default as identity primary key,
  lir_id bigint not null references public.loading_instructions(lir_id) on delete cascade,
  compartment_no smallint not null check (compartment_no between 1 and 5),
  planned_bags integer check (planned_bags is null or planned_bags >= 0),
  actual_bags integer check (actual_bags is null or actual_bags >= 0),
  -- Free-text entry for a hold (e.g. "remaining") kept alongside the parsed number.
  planned_text text,
  actual_text text,
  unique (lir_id, compartment_no)
);

-- Additive migration for databases created before free-text holds existed.
alter table public.loading_instruction_holds add column if not exists planned_text text;
alter table public.loading_instruction_holds add column if not exists actual_text text;

create index if not exists loading_instructions_flight_id_idx on public.loading_instructions(flight_id);
create index if not exists loading_instructions_status_idx on public.loading_instructions(status);

alter table public.loading_instructions enable row level security;
alter table public.loading_instruction_holds enable row level security;

drop policy if exists "public app access" on public.loading_instructions;
drop policy if exists "public app access" on public.loading_instruction_holds;
create policy "public app access" on public.loading_instructions for all to anon, authenticated using (true) with check (true);
create policy "public app access" on public.loading_instruction_holds for all to anon, authenticated using (true) with check (true);

do $$
begin
  begin
    alter publication supabase_realtime add table public.loading_instructions;
  exception
    when duplicate_object then null;
  end;
  begin
    alter publication supabase_realtime add table public.loading_instruction_holds;
  exception
    when duplicate_object then null;
  end;
end $$;
